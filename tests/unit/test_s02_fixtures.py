# ------------------------------------------------------------------ contract 25
def test_oracle_inversion_recovers_the_hidden_constituent(spec: FixtureSpec) -> None:
    base = build_base_model(spec)
    hidden = adapter_updates(spec, base, "hidden")
    partner = adapter_updates(spec, base, "partner")
    merged = linear_merge(base, {"hidden": hidden, "partner": partner}, TEST_MERGE_COEFFICIENTS)
    recovered = oracle_invert_linear(
        merged, base, {"partner": partner}, TEST_MERGE_COEFFICIENTS, "hidden"
    )
    assert set(recovered) == set(hidden)
    for name, truth in hidden.items():
        assert np.allclose(recovered[name], truth, rtol=1e-12, atol=1e-12), name
        assert matrix_rank(recovered[name]) == spec.lora_rank


def test_inversion_may_not_be_handed_the_hidden_adapter(spec: FixtureSpec) -> None:
    base = build_base_model(spec)
    hidden = adapter_updates(spec, base, "hidden")
    merged = linear_merge(base, {"hidden": hidden}, {"hidden": 1.0})
    with pytest.raises(FixtureError, match="may not be supplied"):
        oracle_invert_linear(merged, base, {"hidden": hidden}, {"hidden": 1.0}, "hidden")
    with pytest.raises(FixtureError, match="no non-zero coefficient"):
        oracle_invert_linear(merged, base, {}, {"hidden": 0.0}, "hidden")


# ------------------------------------------------------------------ contract 26
def test_save_load_preserves_the_scientific_values(tmp_path: Path, spec: FixtureSpec) -> None:
    base = build_base_model(spec)
    path = tmp_path / "model.safetensors"
    save_state_dict(path, base)
    reloaded = load_state_dict(path)
    assert set(reloaded) == set(base)
    for name, array in base.items():
        assert reloaded[name].shape == array.shape, name
        # float32 on disk, as a real checkpoint would be; the identity survives the round trip.
        assert np.allclose(reloaded[name], array, rtol=1e-6, atol=1e-7), name


def test_a_reloaded_fixture_still_supports_the_algebra(tmp_path: Path, spec: FixtureSpec) -> None:
    base = build_base_model(spec)
    path = tmp_path / "model.safetensors"
    save_state_dict(path, base)
    reloaded = load_state_dict(path)
    hidden = adapter_updates(spec, reloaded, "hidden")
    merged = linear_merge(reloaded, {"hidden": hidden}, {"hidden": 1.0})
    recovered = oracle_invert_linear(merged, reloaded, {}, {"hidden": 1.0}, "hidden")
    for name, truth in hidden.items():
        assert np.allclose(recovered[name], truth, rtol=1e-10, atol=1e-10), name


# ------------------------------------------------------------------ contract 27
def test_fixture_corruption_is_detected(tmp_path: Path, spec: FixtureSpec) -> None:
    base = build_base_model(spec)
    name = target_parameter_names(spec)[0]
    before = numeric_fingerprint(base[name])

    corrupted = {k: v.copy() for k, v in base.items()}
    corrupted[name][0, 0] += 1e-9
    assert numeric_fingerprint(corrupted[name]) != before
    assert state_fingerprints(corrupted) != state_fingerprints(base)

    path = tmp_path / "model.safetensors"
    save_state_dict(path, base)
    from src.provenance.hashing import ArtifactVerificationError, record_artifact, verify_artifact

    record = record_artifact(tmp_path, "model.safetensors")
    save_state_dict(path, corrupted)
    with pytest.raises(ArtifactVerificationError):
        verify_artifact(tmp_path, record)


