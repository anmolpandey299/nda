# ------------------------------------------------------------------ contract 24
def test_linear_merge_matches_analytic_ground_truth(spec: FixtureSpec) -> None:
    base = build_base_model(spec)
    hidden = adapter_updates(spec, base, "hidden")
    partner = adapter_updates(spec, base, "partner")
    merged = linear_merge(base, {"hidden": hidden, "partner": partner}, TEST_MERGE_COEFFICIENTS)
    for name, array in base.items():
        expected = array.copy()
        if name in hidden:
            expected = (
                expected
                + TEST_MERGE_COEFFICIENTS["hidden"] * hidden[name]
                + TEST_MERGE_COEFFICIENTS["partner"] * partner[name]
            )
        assert np.allclose(merged[name], expected, rtol=0.0, atol=0.0), name
    untouched = [n for n in base if n not in hidden]
    assert untouched, "the merge must leave non-target parameters alone"
    for name in untouched:
        assert np.array_equal(merged[name], base[name])


