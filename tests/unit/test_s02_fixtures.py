def test_the_induced_update_is_exactly_scaled_ba(spec: FixtureSpec) -> None:
    base = build_base_model(spec)
    name = target_parameter_names(spec)[0]
    rows, columns = base[name].shape
    a, b = lora_factors(spec, "hidden", name, (rows, columns))
    assert a.shape == (spec.lora_rank, columns)
    assert b.shape == (rows, spec.lora_rank)
    delta = induced_update(a, b, spec.lora_scaling)
    assert np.array_equal(delta, spec.lora_scaling * (b @ a))
    assert delta.shape == (rows, columns)


def test_rank_32_is_structurally_real(spec: FixtureSpec) -> None:
    """Rank is a property of ΔW, not a label: every targeted update has exactly rank 32."""
    assert spec.lora_rank == 32
    base = build_base_model(spec)
    updates = adapter_updates(spec, base, "hidden")
    assert set(updates) == set(target_parameter_names(spec))
    for name, delta in updates.items():
        assert min(delta.shape) > spec.lora_rank, name
        assert matrix_rank(delta) == spec.lora_rank, name


